package com.example;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

public final class InicializadorBD {
    private static final String ID = "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";

    private static final String[] TABLAS = {
        "CREATE TABLE profesor (" + ID + ", dni VARCHAR(9) NOT NULL, nombre VARCHAR(50) NOT NULL, "
            + "apellidos VARCHAR(80), direccion VARCHAR(100), fecha_nacimiento DATE, "
            + "codigo_postal VARCHAR(5), telefono VARCHAR(15))",
        "CREATE TABLE alumno (" + ID + ", dni VARCHAR(9) NOT NULL, nombre VARCHAR(50) NOT NULL, "
            + "apellidos VARCHAR(80), direccion VARCHAR(100), fecha_nacimiento DATE, "
            + "codigo_postal VARCHAR(5), telefono VARCHAR(15))",
        "CREATE TABLE curso (" + ID + ", codigo VARCHAR(10) NOT NULL, nombre VARCHAR(80) NOT NULL)",
        "CREATE TABLE asignatura (" + ID + ", codigo VARCHAR(10) NOT NULL, nombre VARCHAR(80) NOT NULL, "
            + "horas_semana INTEGER, id_profesor INTEGER NOT NULL REFERENCES profesor(id), "
            + "id_curso INTEGER NOT NULL REFERENCES curso(id))",
        "CREATE TABLE aula (" + ID + ", codigo VARCHAR(10) NOT NULL, piso INTEGER, pupitres INTEGER)",
        "CREATE TABLE matricula (id_alumno INTEGER NOT NULL REFERENCES alumno(id), "
            + "id_asignatura INTEGER NOT NULL REFERENCES asignatura(id), "
            + "calificacion DOUBLE, incidencias VARCHAR(200), PRIMARY KEY (id_alumno, id_asignatura))",
        "CREATE TABLE asignatura_aula (id_asignatura INTEGER NOT NULL REFERENCES asignatura(id), "
            + "id_aula INTEGER NOT NULL REFERENCES aula(id), mes INTEGER NOT NULL, dia INTEGER NOT NULL, "
            + "hora VARCHAR(5) NOT NULL, PRIMARY KEY (id_asignatura, id_aula, mes, dia, hora))"
    };

    private InicializadorBD() { }

    public static void crearTablas() {
        Connection con = ConexionBD.getInstance().getConnection();
        for (String sql : TABLAS) {
            try (Statement st = con.createStatement()) {
                st.execute(sql);
            } catch (SQLException e) {
                System.out.println("Aviso: " + e.getMessage());
            }
        }
    }
}
